// 음성 안내(TTS)에서 읽을 순번 표기.
//
// "1번"처럼 숫자+번으로 쓰면 한국어 특성상 두 가지로 읽힐 수 있다 — 한자어식("일 번")과
// 고유어식("한 번"). 어느 쪽으로 읽을지는 글자만 봐서는 정해지지 않고, 기기/브라우저에 내장된
// 음성엔진(Web Speech API)마다 자체 규칙으로 다르게 정규화해서 읽는다. 그래서 같은 텍스트를
// 보내도 듣는 사람마다 "일번, 이번, 삼번" 또는 "한번, 두번, 세번"으로 서로 다르게 들린다.
// "첫 번째", "두 번째"처럼 고유어 서수를 통째로 문자열에 박아 보내면 숫자 표기 자체가 없어져
// 이 중의성이 사라진다 — 어떤 음성엔진도 이건 한 가지로만 읽는다.
const KO_ORDINALS = [
  "첫", "두", "세", "네", "다섯", "여섯", "일곱", "여덟", "아홉", "열",
  "열한", "열두", "열세", "열네", "열다섯", "열여섯", "열일곱", "열여덟", "열아홉", "스무",
];

// n번째(1부터)를 소리 내어 읽기 좋은 고유어 서수 문자열로. 목록을 벗어나는 긴 조리과정도
// (스물 이후는 고유어 서수가 실생활에서 거의 안 쓰여) 안전하게 "n번째"로 대체한다.
export function speakOrdinal(n: number): string {
  const word = KO_ORDINALS[n - 1];
  return word ? `${word} 번째` : `${n}번째`;
}
