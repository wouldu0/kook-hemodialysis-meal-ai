-- 002_account_recovery.sql — 아이디 찾기 / 비밀번호 찾기용 컬럼 추가
--
-- 로그인 화면의 "아이디 찾기", "비밀번호 찾기"는 이메일 발송 수단이 없는 서비스이므로
-- 본인 확인을 "이름 + 생년월일"로 한다. 기존 스키마에는 프로필에 age(나이)만 있고
-- 생년월일이 없어서(가입 시 입력받아 나이만 계산해 버림) 확인 근거가 없었다.
-- 이 마이그레이션으로 생년월일 원본을 보관한다.
--
-- 서버(server_FOOK.py)는 기동 후 첫 계정 관련 요청 때 이 ALTER를 자동으로 한 번 실행하므로
-- 보통은 이 파일을 직접 돌릴 필요가 없다. 수동으로 미리 적용하고 싶을 때만 실행하면 된다.

ALTER TABLE user_profiles ADD COLUMN IF NOT EXISTS birthdate date;
